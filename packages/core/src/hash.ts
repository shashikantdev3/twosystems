// SHA-256 in plain TypeScript, so the same hashes come out in Node, in the
// Claude Code plugin and anywhere else the core runs. It is used for short
// texts (a question's wording, a state summary, a lock), never for big files.
// Tests check it against node:crypto.
// Part of twosystems, created by Shashikant.

